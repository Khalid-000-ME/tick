import { chromium } from "playwright";
import { readFileSync } from "node:fs";
import { createWalletClient, http, keccak256, toHex } from "viem";
import { privateKeyToAccount } from "viem/accounts";
const PK = keccak256(toHex("tick-participant-21"));
const A = privateKeyToAccount(PK);
const ENV = readFileSync("/Users/khalid/Projects/colosseum/tick/app/.env.local","utf8");
const RPC = ENV.match(/^NEXT_PUBLIC_MONAD_RPC=(.*)$/m)[1].trim().replace(/^["']|["']$/g,"");
const src = readFileSync("record-use.mjs","utf8");
const provider = src.match(/const provider = \(address, rpc, chainHex\) => `([\s\S]*?)`;/)[1]
  .replace("${JSON.stringify(address)}", JSON.stringify(A.address))
  .replace("${JSON.stringify(chainHex)}", '"0x279f"')
  .replace("${JSON.stringify(rpc)}", JSON.stringify(RPC));
const monad={id:10143,name:"Monad",nativeCurrency:{name:"MON",symbol:"MON",decimals:18},rpcUrls:{default:{http:[RPC]}}};
const signer=createWalletClient({account:A,chain:monad,transport:http(RPC)});
const b=await chromium.launch();
const ctx=await b.newContext({viewport:{width:540,height:960},deviceScaleFactor:2,isMobile:true,hasTouch:true});
await ctx.exposeBinding("__tickSend", async (_s,tx)=>{ console.log("SEND", JSON.stringify(tx).slice(0,160)); const h=await signer.sendTransaction({to:tx.to,data:tx.data,value:tx.value?BigInt(tx.value):undefined,gas:tx.gas?BigInt(tx.gas):undefined}); console.log("HASH",h); return h; });
await ctx.exposeBinding("__tickSign", async (_s,m)=>signer.signMessage({message:{raw:m}}));
await ctx.addInitScript(()=>{try{localStorage.setItem("tick.theme","dark")}catch{}});
await ctx.addInitScript(provider);
const p=await ctx.newPage();
p.on("console", m => { const t=m.text(); console.log("CONSOLE:", t.slice(0,200)); });
p.on("pageerror", e => console.log("PAGEERROR:", e.message.slice(0,180)));
await p.goto("http://localhost:3000/trade?feed=BTC%2FUSD&window=30",{waitUntil:"load"});
await p.waitForTimeout(6000);
await p.locator(".amount-presets button").nth(3).click({force:true});
await p.waitForTimeout(800);
console.log("--- clicking Above ---");
const btn = p.locator(".side-picker button.side-up");
console.log("count", await btn.count(), "disabled", await btn.isDisabled().catch(()=>"?"));
await btn.click({force:true});
await p.waitForTimeout(2500);
console.log("after click legend:", await p.locator(".side-picker legend").first().innerText().catch(()=>"?"));
await p.waitForTimeout(2000);
const btns = await p.evaluate(() => [...document.querySelectorAll("button")].map(b=>({t:(b.textContent||"").trim().slice(0,30), cls:b.className, vis:b.offsetParent!==null})).filter(b=>/stake/i.test(b.t)));
console.log("BUTTONS:", JSON.stringify(btns));
const c = p.locator('button:has-text("Stake ABOVE")');
console.log("confirm count", await c.count());
await c.first().click();
await p.waitForTimeout(12000);
const toasts = await p.evaluate(() => [...document.querySelectorAll("[class*=toast],[role=status],[role=alert]")].map(e=>e.textContent.trim()).filter(Boolean));
console.log("TOASTS:", JSON.stringify(toasts).slice(0,300));
await p.waitForTimeout(16000);
console.log("legend:", await p.locator(".side-picker legend").first().innerText().catch(()=>"?"));
await b.close();
